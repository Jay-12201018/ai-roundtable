import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { Database } from '../../../src/main/database/Database';
import { RoomService } from '../../../src/main/room/RoomService';
import { RunService } from '../../../src/main/services/RunService';
import { MockProvider } from '../../../src/main/providers/mock/MockProvider';
import { createPublicMessagesBuilder } from '../../../src/main/context/wirePublicContext';
import { RoomsFeature } from '../../../src/renderer/features/rooms';
const databases: Database[] = [];
afterEach(() => { cleanup(); databases.splice(0).forEach(db => db.close()); });
it('operates the actual rooms feature with RoomService, SQLite and three explicitly configured Mock members', async () => {
  const db = new Database(':memory:'); db.initialize(); databases.push(db);
  db.createProvider({ id: 'explicit-mock', name: '验证专用 Mock', kind: 'mock' });
  const api = new RoomService(db); const selected = vi.fn(); const runSelected = vi.fn();
  const provider = new MockProvider({ tokenDelayMs: 0 }); const stream = vi.spyOn(provider, 'streamChat'); const runs = new RunService(db, provider, createPublicMessagesBuilder());
  render(<RoomsFeature api={api} providers={db.listProviderSummaries()} providerLoadState="ready" onReloadProviders={() => {}} onSelectRoom={selected} onSelectRun={runSelected} onOpenSettings={() => {}} />);
  fireEvent.click(await screen.findByRole('button', { name: '新建房间' }));
  fireEvent.change(screen.getByLabelText('房间名称'), { target: { value: '真实服务注入验证' } });
  fireEvent.change(screen.getByLabelText('房间目标'), { target: { value: '运行与浏览' } });
  fireEvent.click(screen.getByRole('button', { name: '保存房间' })); await screen.findByRole('heading', { name: '真实服务注入验证' });
  const roomId = selected.mock.lastCall![0] as string;
  for (const [i, role] of ['Drafter', 'Critic', 'Synthesizer'].entries()) {
    await waitFor(() => expect((screen.getByRole('button', { name: '新增成员' }) as HTMLButtonElement).disabled).toBe(false));
    fireEvent.click(screen.getByRole('button', { name: '新增成员' }));
    const dialog = screen.getByRole('dialog');
    fireEvent.change(within(dialog).getByLabelText('成员名称'), { target: { value: `配置成员 ${i + 1}` } });
    fireEvent.change(within(dialog).getByLabelText('成员角色'), { target: { value: role } });
    fireEvent.change(within(dialog).getByLabelText('System prompt'), { target: { value: `真实提示 ${i}` } });
    fireEvent.change(within(dialog).getByLabelText('Provider'), { target: { value: 'explicit-mock' } });
    fireEvent.click(within(dialog).getByRole('button', { name: '保存成员' }));
    await screen.findByText(`配置成员 ${i + 1}`);
  }
  const saved = await api.listAgentConfigurations({ roomId }); expect(saved.map(a => a.roleTemplateId)).toEqual(['Drafter', 'Critic', 'Synthesizer']);
  const run = await runs.start({ roomId, task: '配置成员的协作任务', workflowSnapshot: {}, maxTurns: 3 }); await runs.waitForIdle(run.runId);
  expect(stream).toHaveBeenCalledTimes(3);
  expect(stream.mock.calls[2][0].messages.filter(m => m.role === 'assistant')).toHaveLength(2);
  await api.updateAgent({ id: saved[0].id, roomId, displayName: '当前新姓名', roleTemplateId: '新角色', providerId: 'explicit-mock', modelId: 'mock' });
  fireEvent.click(screen.getByRole('button', { name: '历史记录' }));
  fireEvent.click(await screen.findByRole('button', { name: '配置成员的协作任务' }));
  expect(runSelected).toHaveBeenCalledWith(run.runId);
  expect(await screen.findByText('配置成员 1')).toBeTruthy(); expect(screen.queryByText('当前新姓名')).toBeNull();
  expect(runs.getSnapshot(runSelected.mock.lastCall![0]).execution?.membersSnapshot?.[0]).toMatchObject({ displayName: '配置成员 1', roleTemplateId: 'Drafter', modelId: 'mock' });
  await runs.shutdown();
});
